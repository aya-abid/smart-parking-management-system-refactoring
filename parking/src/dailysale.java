    private void getdailysale() {
        try {
            HttpResponse<String> res = Unirest.get("http://localhost:8888/getdailysale").asString();
            String response = res.getBody();
            if (response.isEmpty() == false) {
                StringTokenizer st = new StringTokenizer(response, "~!@");
                int n = st.countTokens();
                int grandtotal =0;
                for (int i = 1; i <= n; i++) {
                    String row = st.nextToken();
                    StringTokenizer st2 = new StringTokenizer(row, "#$%");
                    String parkingbay = st2.nextToken();
                    String dailysale = st2.nextToken();
                   grandtotal += Integer.parseInt(dailysale);
                   al.add(new DailySale(parkingbay, dailysale));
                }
               tftotalsale.setText(grandtotal+"");
            }
        } catch (UnirestException ex) {
            Logger.getLogger(dailysale.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    class DailySale {

        String parkingbay, sale;

        public DailySale(String parkingbay, String sale) {
            this.parkingbay = parkingbay;
            this.sale = sale;
        }

    }

    class DailySaleTableModel extends AbstractTableModel {

        String[] columns = {"Parking Bay", "Daily Sale"};

        @Override
        public int getRowCount() {
            return al.size();
        }

        @Override
        public int getColumnCount() {
            return 2;
        }

        @Override

        public Object getValueAt(int rowIndex, int columnIndex) {
            switch (columnIndex) {
                case 0:
                    return al.get(rowIndex).parkingbay;
                case 1:
                    return al.get(rowIndex).sale;
                default:
                    return null;
            }
        }

        @Override
        public String getColumnName(int column) {
            return columns[column];
        }

    }

