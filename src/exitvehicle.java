    private void btExitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btExitActionPerformed
        try {
            // TODO add your handling code here:
            String ticketno = tfticketno.getText();
            String exitdate = tfdateofexit.getText();
            String exittime = tftimeofexit.getText();
            String rent = tfrent.getText();
            HttpResponse<String> res = Unirest.get("http://localhost:8888/Parkingexit")
                    .queryString("ptid", ticketno)
                    .queryString("exitdate", exitdate)
                    .queryString("exittime", exittime)
                    .queryString("rent", rent).asString();
            String response = res.getBody();
            if (response.equals("success")) {
                JOptionPane.showMessageDialog(rootPane, "Vehicle Exited Successfully!!!!");

                if (objA != null) {
                    objA.load();
                    objA.setVisible(true);
                } else if (objB != null) {
                    objB.load();
                    objB.setVisible(true);
                }
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(rootPane, "Error Occured");
            }

        } catch (UnirestException ex) {
            Logger.getLogger(exitvehicle.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btExitActionPerformed

