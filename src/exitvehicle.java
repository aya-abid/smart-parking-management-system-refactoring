    void loaddata() {
        String ptid = tfticketno.getText();
        if (ptid.isEmpty()) {
            JOptionPane.showMessageDialog(rootPane, "Enter Ticket No.");
        } else {
            try {
                HttpResponse<String> res = Unirest.get("http://localhost:8888/getticketinfo")
                        .queryString("ptid", ptid).asString();
                String response = res.getBody();
                if (response.equals("failed")) {
                    JOptionPane.showMessageDialog(rootPane, "Invalid Ticket No.");
                } else {
                    jpanelexit.setVisible(true);
                    StringTokenizer st = new StringTokenizer(response, "~~~~");
                    String vehicleno = st.nextToken();
                    String vehicletype = st.nextToken();
                    String dateofentry = st.nextToken();
                    String timeofentry = st.nextToken();
                    String location = st.nextToken();
                    int rentperhour = Integer.parseInt(st.nextToken());

                    tfvehicleno.setText(vehicleno);
                    tfvehicletype1.setText(vehicletype);
                    tfdateofentry.setText(dateofentry);
                    tftimeofentry.setText(timeofentry);
                    tflocation.setText(location);

                    SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy HH:mm");

                    Date entrydate = sdf.parse(dateofentry + " " + timeofentry);

                    long oldtime = entrydate.getTime();
                    long newtime = new Date().getTime();

                    long diff = newtime - oldtime;
                    int hours = (int) (((diff / 1000) / 60) / 60);
                    System.out.println("hourss : " + hours);
                    hours = (hours == 0) ? 1 : hours;
                    int rent = hours * rentperhour;
                    tfrent.setText(rent + "");

                    Date currentdate = new Date();
                    SimpleDateFormat sdf1 = new SimpleDateFormat("dd-MM-yyyy");
                    String exitdate = sdf1.format(new Date());
                    sdf1 = new SimpleDateFormat("HH:mm");
                    String exittime = sdf1.format(new Date());

                    tfdateofexit.setText(exitdate);
                    tftimeofexit.setText(exittime);

                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }

        }
    }

