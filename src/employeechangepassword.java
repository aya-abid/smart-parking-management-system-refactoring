    private void btchangepasswordActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btchangepasswordActionPerformed
       
       String oldpassword = pfoldpassword.getText();
        String newpassword = pfnewpassword.getText();
        String confpassword = pfconfpassword.getText();
        if (oldpassword.isEmpty() || confpassword.isEmpty() || newpassword.isEmpty()) {

            JOptionPane.showMessageDialog(this, "all fields are mandatory");

    }                                        
       else if (newpassword.equals(confpassword) == false) {
            JOptionPane.showMessageDialog(this, "new password and confirm password not matched");

        } else {
            try {
                HttpResponse<String> res = Unirest.get("http://localhost:8888/employeechangepassword")
                        .queryString("eid", eid)
                        .queryString("oldpassword", oldpassword)
                        .queryString("newpassword", newpassword).asString();
                String response = res.getBody();
                if (response.equals("success")) {
                    JOptionPane.showMessageDialog(this, "password changed successfully");

                } else {
                    JOptionPane.showMessageDialog(this, "invalid old password");
                }
            } catch (UnirestException ex) {
                Logger.getLogger(employeechangepassword.class.getName()).log(Level.SEVERE, null, ex);

            }
        }
    

        
    }//GEN-LAST:event_btchangepasswordActionPerformed

